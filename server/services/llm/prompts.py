"""
Все промпты для работы с LLM.
Адаптировано: убраны f-string-шаблоны, вынесены в функции с параметрами.
"""


def get_batch_prompt(start_page: int, end_page: int, batch_content: str) -> str:
    """Промпт для стандартного извлечения (таблицы, сущности, суммаризация)."""
    return f"""Ты — эксперт по извлечению данных из технической документации.
Проанализируй содержимое **нескольких последовательных страниц** PDF (с {start_page} по {end_page}).
Твоя задача — извлечь структурированные данные **для каждой страницы отдельно** и вернуть их в виде JSON-массива.

Требования к ответу (строго JSON):
{{
  "pages": [
    {{
      "page_number_md": {start_page},
      "text_entities": [{{"name": "...", "value": "...", "unit": "..."}}],
      "tables": [{{"caption": "...", "headers": [...], "rows": [...], "footnotes": [...]}}],
      "summary": "Краткое описание страницы"
    }},
    ...
  ]
}}

- Количество объектов в массиве "pages" должно быть равно количеству страниц, переданных в содержимом (от {start_page} до {end_page}).
- Если на странице несколько таблиц, создай отдельный объект в массиве `tables` для каждой таблицы. Не объединяй их.
- Если страница не содержит значимых данных, оставь массивы пустыми.
- Числа передавай как числа, не строки.
- Единицы измерения выделяй в отдельное поле `unit`.
- **ОБЯЗАТЕЛЬНО используй номер страницы только из заголовка "## Страница N" (например, 5, 6, 7), а не из колонтитулов документа**. 
- Ответ должен быть только JSON, без пояснений.

Содержимое страниц (границы страниц отмечены комментариями вида <!-- СТРАНИЦА X -->):
{batch_content}"""


def get_batch_tables_prompt(start_page: int, end_page: int, batch_content: str) -> str:
    """Промпт для извлечения сводной таблицы (числовые характеристики)."""
    return f"""Ты — эксперт по извлечению данных из технической документации.
Проанализируй содержимое страниц {start_page}-{end_page}.
Извлеки **все числовые технические характеристики** (название, значение, единицу измерения, номер страницы).
Верни ТОЛЬКО JSON-массив, например:
[
  {{"name": "...", "value": "...", "unit": "...", "source_page": {start_page}}},
  ...
]
В поле source_page укажи **номер страницы** из заголовка "## Страница N".
Игнорируй описательные разделы.
Содержимое:
{batch_content}"""


def get_tables_summary_prompt() -> str:
    """Промпт для создания сводной таблицы из извлечённых данных."""
    return """Ты — эксперт по анализу технической документации.
Тебе предоставлен JSON-объект, содержащий извлечённые таблицы из паспорта изделия.
Твоя задача — создать **единую сводную таблицу**, которая объединяет все значимые технические характеристики.
Характеристики должны быть отсортированы по важности (наиболее важные – вверху).
Формат ответа: JSON-массив объектов, где каждый объект имеет поля:
- "name": название характеристики,
- "value": значение,
- "unit": единицы измерения (если есть),
- "source_page": номер страницы из исходных данных (поле page_md), если он указан.
Если данные дублируются, выбери наиболее полное или точное значение.
**ВАЖНО: в поле source_page указывай номер страницы только из заголовков "## Страница N", а не из колонтитулов документа.**
Верни ТОЛЬКО JSON-массив без каких-либо пояснений."""


def get_bom_prompt(start_page: int, end_page: int, batch_content: str) -> str:
    """Промпт для построения иерархической спецификации (BOM) из документа."""
    template = (
        "Ты — эксперт по составлению иерархических спецификаций материалов (BOM) для промышленного оборудования в системах ТОиР / EAM.\n\n"
        "Твоя задача — проанализировать содержимое страниц {start_page}-{end_page} и построить чёткую иерархическую структуру компонентов изделия в виде BOM-дерева.\n\n"
        "Верни ТОЛЬКО валидный JSON-массив объектов. Каждый объект должен содержать следующие поля:\n"
        '- "level": целое число (0 — для самого верхнего уровня изделия, 1 — для основных узлов/сборочных единиц, 2 и глубже — для подузлов и деталей)\n'
        '- "part_number": номер детали или сборочной единицы (если указан в документе, иначе пустая строка "")\n'
        '- "name": точное название компонента или сборочной единицы\n'
        '- "quantity": количество данного компонента в родительском узле (число)\n'
        '- "unit": единица измерения ("шт", "комп", "м", "кг", "л" и т.д.)\n'
        '- "parent_name": название родительского узла (опционально, помогает при проверке иерархии)\n\n'
        "Правила построения иерархии:\n"
        "- Уровень 0 — всегда одно изделие в целом (например: \"Насос центробежный К 80-50-200\" или \"Ленточный конвейер\").\n"
        "- Уровень 1 — основные сборочные единицы и крупные узлы (рама, привод, редуктор, электродвигатель, конвейерная лента и т.п.).\n"
        "- Уровень 2 и выше — подузлы, детали и крепёж, входящие в узлы верхнего уровня.\n"
        "- Соблюдай реальную вложенность компонентов. Не делай всё на уровне 1.\n\n"
        "Извлекай все значимые компоненты: рама, корпус, привод, двигатель, редуктор, муфта, подшипниковые узлы, ролики, лента, вал, рабочее колесо, крепёж, электрооборудование, защитные кожухи, датчики и т.д.\n\n"
        "Если точный уровень вложенности в документе неочевиден — используй логическую инженерную иерархию.\n\n"
        "Игнорируй: меры безопасности, общие описания, справочную информацию, стандарты, чертежи без текстового описания компонентов.\n\n"
        "Верни ТОЛЬКО чистый JSON-массив объектов, без каких-либо пояснений, комментариев или дополнительного текста.\n\n"
        "Пример структуры:\n"
        "[\n"
        '  {{"level": 0, "part_number": "", "name": "Ленточный конвейер КЛ-500", "quantity": 1, "unit": "шт", "parent_name": ""}},\n'
        '  {{"level": 1, "part_number": "DRV-01", "name": "Приводной блок", "quantity": 1, "unit": "шт", "parent_name": "Ленточный конвейер КЛ-500"}},\n'
        '  {{"level": 2, "part_number": "MOT-150", "name": "Электродвигатель 15 кВт", "quantity": 1, "unit": "шт", "parent_name": "Приводной блок"}},\n'
        '  {{"level": 2, "part_number": "RED-01", "name": "Редуктор цилиндрический", "quantity": 1, "unit": "шт", "parent_name": "Приводной блок"}},\n'
        '  {{"level": 1, "part_number": "", "name": "Конвейерная лента", "quantity": 1, "unit": "м", "parent_name": "Ленточный конвейер КЛ-500"}}\n'
        "]\n\n"
        "Содержимое документа:\n{batch_content}"
    )
    return template.format(start_page=start_page, end_page=end_page, batch_content=batch_content)


def get_tech_card_prompt(has_document: bool = True) -> str:
    """Промпт для формирования технологической карты."""
    instruction = (
        "📄 ТЫ ПОЛУЧИЛ ТЕХНИЧЕСКИЙ ПАСПОРТ для указанной модели. "
        "Используй ТОЛЬКО информацию из этого документа для заполнения таблицы. "
        "Если в документе нет данных по какому-то элементу — оставь соответствующие поля пустыми. "
        "НЕ добавляй информацию из общих знаний, если её нет в документе."
        if has_document else
        "📋 ТЕХНИЧЕСКИЙ ПАСПОРТ НЕ ЗАГРУЖЕН. "
        "Используй свои общие знания по устройству и обслуживанию оборудования данного типа. "
        "Заполни таблицу максимально полно на основе известных тебе данных по указанной модели."
    )

    return f"""Ты инженер, специалист по формированию технологических карт и работ по ТОиР оборудования.

{instruction}

Необходимо заполнить JSON-объект следующего формата:
{{
  "text": "Краткое текстовое описание результата для пользователя",
  "rows": [
    {{
      "Элемент": "Система смазки",
      "Подэлемент": "Картер",
      "Наименование операции": "Осмотр",
      "Краткое содержание работ": "Визуальный осмотр картера на наличие трещин и подтёков",
      "Вид ТОиР": "ТО-1",
      "Периодичность": "4320",
      "Норма времени, часов": "2.0",
      "Количество исполнителей": "1",
      "Профессия/Квалификация": "Слесарь по ремонту автомобилей, 3 разряд",
      "Трудоёмкость, человеко/часов": "2.0",
      "Наименование ТМЦ": "",
      "Количество ТМЦ": "",
      "Единицы измерения ТМЦ": "",
      "Наименование инструменты": "",
      "Средства индивидуальной защиты": "Каска защитная, 1 шт; Очки защитные, 1 шт; Перчатки защитные, 1 пара",
      "Требования по безопасности": "Затормозить технику; Выполнять работы при неработающем двигателе"
    }}
  ]
}}

Правила:
• Каждый новый узел, элемент и подэлемент — в отдельной строке по порядку.
• НЕ вноси как "Элемент" или "Подэлемент": гайки, шайбы, винты, шпильки, хомуты, болты, штифты, шпонки.
• Если в столбцах несколько слов — первое слово всегда существительное, остальные после него.
• Элемент и подэлемент — в единственном числе, именительном падеже.
• Слова нельзя сокращать и заменять синонимами.
• Все 16 полей обязательны, отсутствующие данные оставляй пустой строкой.
• Верни ТОЛЬКО валидный JSON без дополнительных пояснений. Не оборачивай его в Markdown-блоки."""
